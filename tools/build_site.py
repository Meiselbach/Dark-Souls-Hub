"""Build the website data and the desktop-app download.

Run from the repo root:  python tools/build_site.py
Writes docs/data.js (all game data for the site) and docs/downloads/DarkSoulsCompanion.zip.
Re-run it after editing anything in data/ or the desktop app.
"""
import csv
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"

sys.path.insert(0, str(ROOT))
from modules.damage import NOTES  # noqa: E402

DMG_TYPES = ["Physical", "Magic", "Fire", "Lightning"]
STATUS_TYPES = ["Poison", "Toxic", "Bleed"]
SPECIAL_TYPES = ["Divine", "Occult"]


def load_sheet():
    """Same parsing as modules/damage.py:load_sheet, but returns plain JSON-able data."""
    with open(DATA / "boss_weaknesses.csv", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    header = rows[0]
    wanted = DMG_TYPES + STATUS_TYPES + SPECIAL_TYPES
    idx = {name: header.index(name) for name in wanted if name in header}

    bosses = []
    for row in rows[1:]:
        if not row or not row[0].strip():
            break
        bosses.append({"name": row[0].strip(),
                       **{k: (row[i].strip() if i < len(row) else "") for k, i in idx.items()}})

    blocks = []
    for i, row in enumerate(rows):
        if row and re.match(r"\d+ Str /", row[0]):
            head = rows[i + 1]
            blocks.append({"title": row[0], "columns": head[1:],
                           "rows": [[r[0], r[1:]] for r in rows[i + 2:i + 6]],
                           "bonus": rows[i + 6][1:], "total": rows[i + 7][1:]})
        if row and row[0].startswith("Longsword DmgReduction"):
            blocks.append({"title": "Target damage reduction %", "columns": rows[i][1:],
                           "rows": [[r[0], r[1:]] for r in rows[i + 1:i + 5]], "bonus": None, "total": None})
    return bosses, blocks


def read(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def build_data():
    bosses, blocks = load_sheet()
    payload = {
        "weapons": read("weapons.json"),
        "bosses": read("bosses.json"),
        "classes": read("classes.json"),
        "links": read("links.json"),
        "weakness": {"bosses": bosses, "blocks": blocks, "notes": NOTES},
    }
    DOCS.mkdir(exist_ok=True)
    (DOCS / "data.js").write_text(
        "// Generated by tools/build_site.py. Do not edit by hand.\n"
        "window.DS = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8")
    print(f"docs/data.js: {len(payload['weapons'])} weapons, {len(payload['bosses'])} bosses, "
          f"{len(bosses)} weakness rows")


def build_zip():
    out = DOCS / "downloads" / "DarkSoulsCompanion.zip"
    out.parent.mkdir(parents=True, exist_ok=True)
    include = ["main.py", "README.md", "Start DS Companion.bat"]
    folders = ["core", "modules", "data"]
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in include:
            z.write(ROOT / name, f"DarkSoulsCompanion/{name}")
        for folder in folders:
            for p in sorted((ROOT / folder).rglob("*")):
                if p.is_file() and "__pycache__" not in p.parts:
                    z.write(p, f"DarkSoulsCompanion/{p.relative_to(ROOT).as_posix()}")
        z.writestr("DarkSoulsCompanion/save/.gitkeep", "")
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    build_data()
    build_zip()
