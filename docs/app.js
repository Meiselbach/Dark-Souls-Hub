const EARLY_COSTS = { 2: 673, 3: 690, 4: 707, 5: 724, 6: 741, 7: 758, 8: 775, 9: 793, 10: 811, 11: 829, 12: 847 };
const levelCost = (lvl) => {
  if (lvl <= 1) return 0;
  if (EARLY_COSTS[lvl]) return EARLY_COSTS[lvl];
  return Math.floor(0.02 * lvl ** 3 + 3.06 * lvl ** 2 + 105.6 * lvl - 895 + 0.5);
};
const soulsBetween = (a, b) => { let t = 0; for (let l = a + 1; l <= b; l++) t += levelCost(l); return t; };
const attunementSlots = (att) => ([[50, 10], [41, 9], [34, 8], [28, 7], [23, 6], [19, 5], [16, 4], [14, 3], [12, 2], [10, 1]].find(([t]) => att >= t)?.[1] ?? 0);

