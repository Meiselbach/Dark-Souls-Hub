const DMG = ["Physical", "Magic", "Fire", "Lightning"];
const STATUS = ["Poison", "Toxic", "Bleed"];
const SPECIAL = ["Divine", "Occult"];

function dsDamage(ar, def) {
  if (ar <= 0) return 0;
  if (def <= 0) return ar * 0.9;
  const r = ar / def;
  let m;
  if (r < 0.125) m = 0.1;
  else if (r < 1) m = 19.2 / 49 * (r - 0.125) ** 2 + 0.1;
  else if (r < 2.5) m = -0.4 / 3 * (r - 2.5) ** 2 + 0.7;
  else if (r < 8) m = -0.8 / 121 * (r - 8) ** 2 + 0.9;
  else m = 0.9;
  return ar * m;
}
const num = (cell) => { const m = /^\s*([\d.]+)/.exec(cell || ""); return m ? parseFloat(m[1]) : null; };
const HP = Object.fromEntries(BOSSES.map((b) => [b.name, b.hp]));
function bossHp(name) {
  if (HP[name]) return HP[name];
  const first = name.split(",")[0].split(/\s+/)[0];
  const hit = Object.keys(HP).find((k) => k.includes(first));
  return hit ? HP[hit] : null;
}

