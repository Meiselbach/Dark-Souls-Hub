let weakSort = { key: null, desc: false }, weakMode = "row";

function renderWeak() {
  const cols = ["Boss", ...DMG, "Best", ...STATUS, ...SPECIAL];
  let list = [...WEAK.bosses];
  if (weakSort.key) {
    const k = weakSort.key, dir = weakSort.desc ? -1 : 1;
    list.sort((a, b) => {
      if (k === "Boss" || k === "Best") return (k === "Boss" ? a.name.localeCompare(b.name) : a.Best.localeCompare(b.Best)) * dir;
      const x = num(a[k]), y = num(b[k]);
      return x == null && y == null ? 0 : x == null ? 1 : y == null ? -1 : (x - y) * dir;
    });
  }
  const ranges = {};
  [...DMG, ...STATUS].forEach((t) => {
    const vs = WEAK.bosses.map((b) => num(b[t])).filter((v) => v != null);
    ranges[t] = vs.length ? [Math.min(...vs), Math.max(...vs)] : [0, 1];
  });
  const head = cols.map((c) => `<th scope="col" data-sort="${c}" ${weakSort.key === c ? `aria-sort="${weakSort.desc ? "descending" : "ascending"}"` : ""}>${c}${weakSort.key === c ? (weakSort.desc ? " ▼" : " ▲") : ""}</th>`).join("");
  const body = list.map((b) => {
    const present = DMG.map((t) => num(b[t])).filter((v) => v != null);
    const lo = Math.min(...present), hi = Math.max(...present);
    return `<tr>${cols.map((c) => {
      const text = c === "Boss" ? b.name : b[c] ?? "";
      let cls = "";
      if (DMG.includes(c) || STATUS.includes(c)) {
        const v = num(text);
        if (v == null) cls = "t-none";
        else if (weakMode === "row" && DMG.includes(c)) cls = v === lo ? "t-good" : v === hi && hi !== lo ? "t-bad" : "";
        else if (weakMode === "col") {
          const [mn, mx] = ranges[c], f = mx > mn ? (v - mn) / (mx - mn) : 0;
          cls = f < 0.15 ? "t-good" : f > 0.6 ? "t-bad" : "";
        }
      } else if (c === "Best") cls = `el-${text}`;
      else if (SPECIAL.includes(c)) cls = text.includes("weak") ? "weak" : "";
      return `<td class="${cls}">${esc(text)}</td>`;
    }).join("")}</tr>`;
  }).join("");
  const counts = DMG.map((t) => WEAK.bosses.filter((b) => b.Best === t).length);
  const foot = `<tfoot><tr><td>Bosses weakest to it</td>${counts.map((n) => `<td>${n}</td>`).join("")}<td colspan="${cols.length - 1 - DMG.length}"></td></tr></tfoot>`;
  html($("#weak-table"), `<thead><tr>${head}</tr></thead><tbody>${body}</tbody>${foot}`);
  $$("#weak-table th[data-sort]").forEach((th) => th.addEventListener("click", () => {
    const k = th.dataset.sort;
    weakSort = weakSort.key === k ? { key: k, desc: !weakSort.desc } : { key: k, desc: false };
    renderWeak();
  }));
}

const fnum = (el) => { const v = parseFloat(String(el.value).replace(",", ".")); return Number.isFinite(v) ? v : null; };

function dcHit(defenses) {
  const mult = (fnum($("#dc-mv")) ?? 100) / 100 * ((fnum($("#dc-bonus")) ?? 100) / 100);
  const parts = {};
  let totalAr = 0, total = 0;
  for (const t of DMG) {
    const ar = (fnum($(`#dc-ar-${t}`)) ?? 0) * mult;
    totalAr += ar;
    const d = defenses[t];
    const dmg = d == null ? null : dsDamage(ar, d);
    parts[t] = [ar, dmg];
    if (dmg != null) total += dmg;
  }
  return { parts, total, totalAr };
}

function renderCalc() {
  const defenses = {};
  DMG.forEach((t) => { const el = $(`#dc-df-${t}`); defenses[t] = el.value.trim() === "" ? null : fnum(el) ?? 0; });
  const { parts, total, totalAr } = dcHit(defenses);
  const pad = (s, n) => String(s).padStart(n);
  let out = `<span class="m">${"Type".padEnd(11)}${pad("AR", 9)}${pad("Def", 9)}${pad("Damage", 10)}${pad("Reduced", 10)}</span>\n`;
  for (const t of DMG) {
    const [ar, dmg] = parts[t];
    if (ar === 0) continue;
    out += dmg == null
      ? `${t.padEnd(11)}${pad(ar.toFixed(1), 9)}${pad("---", 9)}${pad("immune", 10)}\n`
      : `${t.padEnd(11)}${pad(ar.toFixed(1), 9)}${pad(defenses[t].toFixed(0), 9)}${pad(dmg.toFixed(1), 10)}${pad(((1 - dmg / ar) * 100).toFixed(1) + "%", 10)}\n`;
  }
  out += `\n<span class="big">Damage per hit: ${total.toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 })}</span>\n`;
  if (totalAr) out += `Damage reduced: ${((1 - total / totalAr) * 100).toFixed(1)}% of ${totalAr.toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 })} AR\n`;
  const hp = fnum($("#dc-hp"));
  if (hp && total) {
    out += `Hits to kill:   ${(hp / total).toFixed(2)}  (${Math.ceil(hp / total)} hits)\n`;
    out += `<span class="m">Effective HP:   ${(totalAr ? hp / (total / totalAr) : 0).toLocaleString("en-US", { minimumFractionDigits: 1, maximumFractionDigits: 1 })}</span>\n`;
  }
  html($("#dc-out"), out);

  const rows = WEAK.bosses.map((b) => {
    const d = Object.fromEntries(DMG.map((t) => [t, num(b[t])]));
    const bossHpVal = bossHp(b.name);
    if (DMG.every((t) => d[t] == null)) return `<tr class="muted"><td>${esc(b.name)}</td><td class="num">—</td><td class="num">—</td><td class="num">${bossHpVal ?? "—"}</td><td class="num">—</td></tr>`;
    const r = dcHit(d);
    return `<tr><td>${esc(b.name)}</td><td class="num">${r.total.toFixed(1)}</td><td class="num">${r.totalAr ? Math.round(r.total / r.totalAr * 100) + "%" : "—"}</td><td class="num">${bossHpVal ?? "—"}</td><td class="num">${bossHpVal && r.total ? Math.ceil(bossHpVal / r.total) : "—"}</td></tr>`;
  }).join("");
  html($("#dc-table"), `<thead><tr><th>Boss</th><th class="num">Damage / hit</th><th class="num">% of AR</th><th class="num">HP (approx)</th><th class="num">Hits to kill</th></tr></thead><tbody>${rows}</tbody>`);
}

