function exportCSV() {
  const names = BOSSES.map((b) => b.name);
  const q = (v) => { v = String(v ?? ""); return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v; };
  const lines = [["Date", "Weapon", "Completed", "Time", "Non-boss deaths", "Notes", ...names.map((n) => `${n} deaths`), ...names.map((n) => `${n} killed`)]];
  for (const r of tracker.runs) {
    const d = r.boss_deaths || {}, k = new Set(r.killed || []);
    lines.push([r.date, r.weapon, !!r.completed, r.time || "", r.non_boss_deaths || 0, r.notes || "", ...names.map((n) => d[n] || 0), ...names.map((n) => k.has(n))]);
  }
  download("ds_run_log.csv", lines.map((l) => l.map(q).join(",")).join("\r\n"), "text/csv");
}

async function importJSON(e) {
  const file = e.target.files[0];
  e.target.value = "";
  if (!file) return;
  try {
    const data = JSON.parse(await file.text());
    if (!data || !Array.isArray(data.runs)) throw new Error("no runs list");
    const runs = data.runs.filter((r) => r && typeof r.weapon === "string").map((r) => ({
      id: String(r.id || uuid()), weapon: r.weapon, date: r.date || "", time: r.time || "", completed: !!r.completed,
      killed: Array.isArray(r.killed) ? r.killed : [], boss_deaths: r.boss_deaths && typeof r.boss_deaths === "object" ? r.boss_deaths : {},
      non_boss_deaths: Number(r.non_boss_deaths) || 0, notes: r.notes || "",
    }));
    if (!confirm(`Replace your ${tracker.runs.length} saved runs with ${runs.length} runs from "${file.name}"?`)) return;
    tracker.state = { runs, excluded: Array.isArray(data.excluded) ? data.excluded : [], seed: Number.isFinite(data.seed) ? data.seed : 1 };
    tracker.save();
    renderChallenge();
  } catch (err) {
    alert(`Could not read that file: ${err.message}. Pick a challenge.json exported from this site or the desktop app.`);
  }
}

