const uuid = () => (crypto.randomUUID ? crypto.randomUUID().replace(/-/g, "") : Math.random().toString(16).slice(2) + Date.now().toString(16));

function download(filename, text, type) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = Object.assign(document.createElement("a"), { href: url, download: filename });
  document.body.append(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Small deterministic PRNG so a seed always gives the same roulette pick. */
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Render a sortable table. cols: [{key,label,num,render}], rows: objects (row.cls = row class). */
function sortableTable(table, cols, rows, sort, onSort, extra = {}) {
  if (sort.key) {
    const dir = sort.desc ? -1 : 1;
    rows = [...rows].sort((a, b) => {
      const x = a[sort.key], y = b[sort.key];
      if (x == null && y == null) return 0;
      if (x == null) return 1;
      if (y == null) return -1;
      return (typeof x === "number" && typeof y === "number" ? x - y : String(x).localeCompare(String(y))) * dir;
    });
  }
  const arrow = (c) => (sort.key === c.key ? (sort.desc ? " ▼" : " ▲") : "");
  const head = cols.map((c) => `<th scope="col" class="${c.num ? "num" : ""}" data-sort="${c.key}" ${sort.key === c.key ? `aria-sort="${sort.desc ? "descending" : "ascending"}"` : ""}>${esc(c.label)}${arrow(c)}</th>`).join("");
  const body = rows.map((r, i) =>
    `<tr class="${r.cls || ""}" data-i="${i}" data-id="${esc(r.id ?? "")}">${cols.map((c) =>
      `<td class="${c.num ? "num" : ""} ${c.wrap ? "wrap" : ""} ${c.cls || ""}">${c.render ? c.render(r) : esc(r[c.key] ?? "")}</td>`).join("")}</tr>`).join("");
  html(table, `<thead><tr>${head}</tr></thead><tbody>${body || `<tr><td class="empty" colspan="${cols.length}">${esc(extra.empty || "Nothing here yet.")}</td></tr>`}</tbody>`);
  $$("th[data-sort]", table).forEach((th) => th.addEventListener("click", () => {
    const key = th.dataset.sort;
    onSort(sort.key === key ? { key, desc: !sort.desc } : { key, desc: false });
  }));
}

