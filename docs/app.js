const MILESTONES = [1, 5, 10, 25, 50, 75, 100];
const WEAPON_BY_NAME = Object.fromEntries(WEAPONS.map((w) => [w.name, w]));
const DLC_BOSSES = new Set(BOSSES.filter((b) => b.dlc).map((b) => b.name));

const tracker = {
  state: store.get("dsh.challenge", null) || { runs: [], excluded: [], seed: 1 },
  save() { if (!store.set("dsh.challenge", this.state)) flashSaveError(); },
  get runs() { return this.state.runs; },
  get excluded() { return new Set(this.state.excluded || []); },
  activeWeapons() { const ex = this.excluded; return WEAPONS.filter((w) => !ex.has(w.name)); },
  completedWeapons() {
    const active = new Set(this.activeWeapons().map((w) => w.name));
    return new Set(this.runs.filter((r) => r.completed && active.has(r.weapon)).map((r) => r.weapon));
  },
  remainingWeapons() { const done = this.completedWeapons(); return this.activeWeapons().filter((w) => !done.has(w.name)); },
  runDeaths: (r) => Object.values(r.boss_deaths || {}).reduce((a, b) => a + b, 0) + (r.non_boss_deaths || 0),
  upsertRun(run) {
    const i = this.runs.findIndex((r) => r.id === run.id);
    if (i >= 0) this.runs[i] = run; else this.runs.push(run);
    this.save();
  },
  deleteRun(id) { this.state.runs = this.runs.filter((r) => r.id !== id); this.save(); },
  toggleExcluded(name) {
    const ex = this.excluded;
    ex.has(name) ? ex.delete(name) : ex.add(name);
    this.state.excluded = [...ex].sort();
    this.save();
  },
  roulette() {
    const pool = this.remainingWeapons().map((w) => w.name).sort();
    if (!pool.length) return null;
    const rnd = mulberry32(this.state.seed ?? 1);
    return WEAPON_BY_NAME[pool[Math.floor(rnd() * pool.length)]];
  },
  bestTime(weapon) {
    const t = this.runs.filter((r) => r.completed && r.weapon === weapon).map((r) => parseTime(r.time)).filter((x) => x != null);
    return t.length ? Math.min(...t) : null;
  },
  bossTable() {
    const table = {};
    const row = (n) => (table[n] ??= { kills: 0, deaths: 0, deathless: 0, worst: 0 });
    BOSSES.forEach((b) => row(b.name));
    for (const r of this.runs) {
      const deaths = r.boss_deaths || {};
      for (const [name, d] of Object.entries(deaths)) { const t = row(name); t.deaths += d; t.worst = Math.max(t.worst, d); }
      for (const name of r.killed || []) { const t = row(name); t.kills++; if (!deaths[name]) t.deathless++; }
    }
    return table;
  },
  stats() {
    const runs = this.runs;
    const completed = runs.filter((r) => r.completed);
    const active = this.activeWeapons();
    const done = this.completedWeapons();
    const times = completed.map((r) => parseTime(r.time)).filter((t) => t != null);
    const avg = times.length ? times.reduce((a, b) => a + b, 0) / times.length : null;
    const remaining = active.length - done.size;
    const bosses = this.bossTable();
    const entries = Object.entries(bosses);
    const bossDeaths = entries.reduce((a, [, v]) => a + v.deaths, 0);
    const nonBoss = runs.reduce((a, r) => a + (r.non_boss_deaths || 0), 0);
    const dlcDeaths = entries.filter(([k]) => DLC_BOSSES.has(k)).reduce((a, [, v]) => a + v.deaths, 0);
    const maxBy = (arr, f) => arr.reduce((best, e) => (best == null || f(e) > f(best) ? e : best), null);
    const nemesis = maxBy(entries, ([, v]) => v.deaths);
    const worst = maxBy(entries.filter(([, v]) => v.kills), ([, v]) => v.deaths / v.kills);
    const mostOne = maxBy(entries, ([, v]) => v.worst);
    const timed = completed.filter((r) => parseTime(r.time) != null);
    const bestRun = maxBy(timed, (r) => -parseTime(r.time));
    const target = active.length;
    const nextMs = MILESTONES.find((m) => m > done.size && m < target) ?? target;
    return {
      weaponsDone: done.size, weaponsLeft: remaining, weaponsTotal: target,
      completion: target ? done.size / target * 100 : 0,
      runsCompleted: completed.length, runsTotal: runs.length,
      deaths: bossDeaths + nonBoss, avgTime: avg,
      estHours: avg ? remaining * avg / 3600 : null,
      bossesSlain: runs.reduce((a, r) => a + (r.killed || []).length, 0),
      deathlessKills: entries.reduce((a, [, v]) => a + v.deathless, 0),
      noDeathRuns: completed.filter((r) => this.runDeaths(r) === 0).length,
      dlcDeaths, nonBoss,
      nemesis: nemesis && nemesis[1].deaths ? `${nemesis[0]} (${nemesis[1].deaths})` : "—",
      worstBoss: worst ? `${worst[0]} (${(worst[1].deaths / worst[1].kills).toFixed(1)}/kill)` : "—",
      mostOne: mostOne && mostOne[1].worst ? `${mostOne[1].worst} (${mostOne[0]})` : "—",
      bestRun: bestRun ? `${bestRun.weapon} (${fmtTime(parseTime(bestRun.time))})` : "—",
      nextMilestone: remaining ? `${nextMs} weapons` : "Challenge complete!",
    };
  },
};

