function lvTargets() {
  const out = {};
  for (const s of LV_STATS) {
    const raw = $(`#lv-in-${s}`).value.trim();
    const v = parseInt(raw, 10);
    out[s] = raw === "" || !Number.isFinite(v) ? null : Math.max(1, Math.min(99, v));
  }
  return out;
}
function lvBuild(cls, targets) {
  const c = LV_CLASSES[cls];
  let added = 0, wasted = 0;
  for (const s of LV_STATS) {
    const diff = (targets[s] ?? c.stats[s]) - c.stats[s];
    diff >= 0 ? (added += diff) : (wasted -= diff);
  }
  return [c.level + added, wasted];
}
function lvSet(values) {
  const base = LV_CLASSES[$("#lv-class").value].stats;
  LV_STATS.forEach((s) => { $(`#lv-in-${s}`).value = values?.[s] ?? base[s]; });
  renderLevels();
}

